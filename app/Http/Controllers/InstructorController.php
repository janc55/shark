     * Store a newly created resource in storage.
     *
     * @param  \Illuminate\Http\Request  $request
     * @return \Illuminate\Http\Response
     */
    public function store(Request $request)
    {
        $instructor = new Instructor;
        $instructor->ins_nombre = $request->ins_nombre;
        $instructor->ins_apellidos = $request->ins_apellidos;
        $instructor->ins_correo = $request->ins_correo;
        $instructor->ins_celular = $request->ins_celular;
        $instructor->ins_sexo = $request->ins_sexo;
        
      

        $instructor->save();
        return redirect("/instructor")->with("status", "Instructor creado correctamente");
    }

