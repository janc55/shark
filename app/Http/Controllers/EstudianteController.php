     * Store a newly created resource in storage.
     *
     * @param  \Illuminate\Http\Request  $request
     * @return \Illuminate\Http\Response
     */
    public function store(Request $request)
    {
    
        $estudiante = new Estudiante;
        $estudiante->est_nombre = $request->nombre;
        $estudiante->est_apellidos = $request->apellidos;
        $estudiante->est_correo = $request->correo;
        $estudiante->est_celular = $request->celular;
        $estudiante->est_sexo = $request->sexo;
        
      

        $estudiante->save();
        return redirect("/estudiante")->with("status", "Estudiante creado correctamente");
    }

